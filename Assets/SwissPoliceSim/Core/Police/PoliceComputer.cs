using System;
using System.Collections.Generic;
using System.Globalization;
using SwissPoliceSim.Core.Legal;
using SwissPoliceSim.Core.Npc;

namespace SwissPoliceSim.Core.Police
{
    [Flags] public enum QueryFlags { None = 0, Stolen = 1, Wanted = 2, NoInsurance = 4, InspectionOverdue = 8, LicenseInvalid = 16, VehicleDefect = 32, Priors = 64, IllegalItemNote = 128 }

    public sealed class QueryResult
    {
        public bool Found; public string Title = ""; public readonly List<string> Lines = new List<string>(); public QueryFlags Flags;
        public LegalAssessment Assessment; public Citizen Person;
        public override string ToString() => Title + "\n" + string.Join("\n", Lines);
    }

    public sealed class QueryLogEntry { public double GameSeconds; public string Kind = "", Subject = "", Reason = ""; public bool Lawful; }

    /// <summary>
    /// Police computer (JANUS/RIPOL/FABER-style, fictional data): plate and person queries answered from the same <see cref="Citizen"/> truth the NPC
    /// dialogue uses, so what the screen shows is consistent with what people say. Queries need an official purpose and are logged and
    /// assessed (data protection: curiosity queries are unlawful).
    /// </summary>
    public sealed class PoliceComputer
    {
        readonly Dictionary<string, Citizen> _byPlate = new Dictionary<string, Citizen>(StringComparer.OrdinalIgnoreCase);
        readonly Dictionary<string, Citizen> _byName = new Dictionary<string, Citizen>(StringComparer.OrdinalIgnoreCase);
        public readonly List<QueryLogEntry> Log = new List<QueryLogEntry>();
        public readonly HashSet<string> WantedPlates = new HashSet<string>(StringComparer.OrdinalIgnoreCase);   // active vehicle alerts (Fahndung)
        public double Now;
        /// <summary>Optional hook: resolve a plate to the person of a currently simulated vehicle so the computer agrees with what the driver says.</summary>
        public Func<string, Citizen> Resolver;

        static string NormPlate(string p) => (p ?? "").Replace(" ", "").Replace(".", "").Replace("-", "").ToUpperInvariant();

        public void Register(Citizen c)
        {
            if (c == null) return;
            if (!string.IsNullOrEmpty(c.Vehicle?.Plate)) _byPlate[NormPlate(c.Vehicle.Plate)] = c;
            _byName[Key(c.FirstName, c.LastName, c.Birthdate)] = c;
        }

        static string Key(string f, string l, string b) => (f ?? "").Trim() + "|" + (l ?? "").Trim() + "|" + (b ?? "").Trim();

        /// <summary>Deterministic citizen for a plate that was never generated by a scenario (random roadside check): same plate → same person.</summary>
        public static Citizen Synthesize(string plate)
        {
            string np = NormPlate(plate); int seed = 17; foreach (char ch in np) seed = seed * 31 + ch;
            string canton = np.Length >= 2 && char.IsLetter(np[0]) && char.IsLetter(np[1]) ? np.Substring(0, 2) : "BE";
            var r = new Random(seed);
            var c = CitizenFactory.Create(seed, canton, "", plate, r.Next(5), r.Next(12));
            double x = r.NextDouble();
            CitizenFactory.ApplyDriverTruth(c, false, 0f, r.NextDouble() < 0.006, r.NextDouble() < 0.012, r.NextDouble() < 0.012, r.NextDouble() < 0.04, r.NextDouble() < 0.004, seed);
            c.Vehicle.Stolen = r.NextDouble() < 0.004; c.Vehicle.Plate = plate;
            return c;
        }

        public Citizen Resolve(string plate)
        {
            string np = NormPlate(plate); if (np.Length < 3) return null;
            if (_byPlate.TryGetValue(np, out var c)) return c;
            c = Resolver?.Invoke(plate) ?? Synthesize(plate); Register(c); return c;
        }

        // ------------------------------------------------------------------ queries
        public QueryResult QueryPlate(string plate, string reason, LegalContext ctx = null)
        {
            var res = new QueryResult { Title = "Fahrzeugabfrage " + plate };
            res.Assessment = Assess(OfficerAct.QueryVehicleData, reason, ctx);
            Log.Add(new QueryLogEntry { GameSeconds = Now, Kind = "Fahrzeug", Subject = plate, Reason = reason ?? "", Lawful = res.Assessment.Lawful });
            var c = Resolve(plate); if (c == null) { res.Lines.Add("Kein Eintrag. Kontrollschild unvollständig."); return res; }
            res.Found = true; res.Person = c; var v = c.Vehicle;
            res.Lines.Add($"Kontrollschild: {v.Plate}   Fahrzeug: {v.Make} {v.Model}, {v.Colour}, Jg. {v.Year}");
            res.Lines.Add($"Halter: {c.FirstName} {c.LastName}, {c.Birthdate}, {c.Address}, {c.Municipality} ({c.Canton})");
            res.Lines.Add("Fahrzeugausweis: gültig");
            if (v.InspectionOverdue) { res.Flags |= QueryFlags.InspectionOverdue; res.Lines.Add("MFK: ÜBERFÄLLIG (letzte Prüfung " + (string.IsNullOrEmpty(v.LastInspection) ? "unbekannt" : v.LastInspection) + ")"); } else res.Lines.Add("MFK: in Ordnung");
            if (!v.Insured) { res.Flags |= QueryFlags.NoInsurance; res.Lines.Add("Haftpflichtversicherung: KEINE GÜLTIGE DECKUNG gemeldet (Art. 63 SVG)"); } else res.Lines.Add("Haftpflichtversicherung: gemeldet");
            if (v.Stolen || WantedPlates.Contains(NormPlate(v.Plate))) { res.Flags |= QueryFlags.Stolen; res.Lines.Add("*** FAHNDUNG: Fahrzeug zur Fahndung ausgeschrieben ***"); }
            if (c.Wanted) { res.Flags |= QueryFlags.Wanted; res.Lines.Add("*** HALTER AUSGESCHRIEBEN: " + c.WantedReason + " ***"); }
            if (c.License != LicenseStatus.Valid) { res.Flags |= QueryFlags.LicenseInvalid; res.Lines.Add("Führerausweis des Halters: " + LicenseText(c.License)); }
            return res;
        }

        public QueryResult QueryPerson(string firstName, string lastName, string birthdate, string reason, LegalContext ctx = null)
        {
            var res = new QueryResult { Title = $"Personenabfrage {firstName} {lastName}" };
            res.Assessment = Assess(OfficerAct.QueryPersonData, reason, ctx);
            Log.Add(new QueryLogEntry { GameSeconds = Now, Kind = "Person", Subject = firstName + " " + lastName, Reason = reason ?? "", Lawful = res.Assessment.Lawful });
            if (!_byName.TryGetValue(Key(firstName, lastName, birthdate), out var c))
            {   // name-only fallback
                foreach (var kv in _byName) if (string.Equals(kv.Value.FirstName, firstName?.Trim(), StringComparison.OrdinalIgnoreCase) && string.Equals(kv.Value.LastName, lastName?.Trim(), StringComparison.OrdinalIgnoreCase) && (string.IsNullOrWhiteSpace(birthdate) || kv.Value.Birthdate == birthdate)) { c = kv.Value; break; }
            }
            if (c == null) { res.Lines.Add("Keine Person mit diesen Angaben gefunden."); return res; }
            res.Found = true; res.Person = c;
            res.Lines.Add($"{c.FirstName} {c.LastName}, geb. {c.Birthdate}, {c.Nationality}, {c.Occupation}");
            res.Lines.Add($"Wohnsitz: {c.Address}, {c.Municipality} ({c.Canton})");
            res.Lines.Add("Führerausweis: " + LicenseText(c.License) + (c.License == LicenseStatus.Valid ? $" (Kat. {c.LicenseCategory}, gültig bis {c.LicenseExpires})" : ""));
            if (c.License != LicenseStatus.Valid) res.Flags |= QueryFlags.LicenseInvalid;
            foreach (var m in c.AdminMeasures) res.Lines.Add("Administrativmassnahme: " + m);
            if (c.Wanted) { res.Flags |= QueryFlags.Wanted; res.Lines.Add("*** AUSSCHREIBUNG: " + c.WantedReason + " ***"); }
            if (c.Record.Count > 0) { res.Flags |= QueryFlags.Priors; foreach (var e in c.Record) res.Lines.Add($"Eintrag {e.Date}: {e.Offence} – {e.Outcome}"); } else res.Lines.Add("Keine polizeilichen Einträge.");
            if (!string.IsNullOrEmpty(c.Vehicle?.Plate)) res.Lines.Add("Eingelöstes Fahrzeug: " + c.Vehicle.Plate + " (" + c.Vehicle.Make + " " + c.Vehicle.Model + ")");
            return res;
        }

        static string LicenseText(LicenseStatus s)
        {
            switch (s) { case LicenseStatus.Valid: return "gültig"; case LicenseStatus.Expired: return "ABGELAUFEN"; case LicenseStatus.Suspended: return "ENTZOGEN (Sicherungsentzug/Warnentzug)"; case LicenseStatus.Withdrawn: return "ZURÜCKGEZOGEN"; default: return "KEIN FÜHRERAUSWEIS"; }
        }

        LegalAssessment Assess(OfficerAct act, string reason, LegalContext ctx)
        {
            ctx = ctx ?? new LegalContext(); ctx.OfficialPurpose = !string.IsNullOrWhiteSpace(reason);
            return LegalSystem.Assess(act, ctx);
        }
    }
}
